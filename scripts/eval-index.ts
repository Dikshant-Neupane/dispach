#!/usr/bin/env bun
/**
 * The evals index: one generated page over every eval and every public claim.
 *
 *   bun scripts/eval-index.ts            write evals/README.md and evals/index.json
 *   bun scripts/eval-index.ts --check    fail when either is stale, or a claim's evidence is missing
 *
 * `evals/CLAIMS.md` is hand-written and is the source; this only reads it. The check is what makes
 * the register binding: a row marked `verified` must name at least one file that exists, so a result
 * deleted or renamed fails CI instead of leaving a public number pointing at nothing.
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const ROOT = resolve(import.meta.dirname, "..")
const EVALS = join(ROOT, "evals")
const CHECK = process.argv.includes("--check")

export interface Claim {
    readonly section: string
    readonly claim: string
    readonly evidence: string
    readonly scope: string
    readonly limitation: string
    readonly status: string
    readonly files: readonly string[]
}

export interface EvalEntry {
    readonly name: string
    readonly title: string
    readonly results: readonly string[]
    readonly measuredAt?: string
}

/** Cells of a markdown table row, with `|` inside backticks left alone. */
function cells(line: string): string[] {
    const out: string[] = []
    let current = ""
    let code = false
    for (const char of line.trim().replace(/^\|/, "").replace(/\|$/, "")) {
        if (char === "`") code = !code
        if (char === "|" && !code) {
            out.push(current.trim())
            current = ""
        } else current += char
    }
    out.push(current.trim())
    return out
}

export function parseClaims(markdown: string): Claim[] {
    const claims: Claim[] = []
    let section = ""
    for (const line of markdown.split("\n")) {
        if (line.startsWith("## ")) section = line.slice(3).trim()
        if (!line.startsWith("| ") || line.startsWith("| Claim") || line.startsWith("| ---"))
            continue
        const row = cells(line)
        if (row.length !== 5) continue
        const [claim = "", evidence = "", scope = "", limitation = "", status = ""] = row
        const files = [...evidence.matchAll(/`([\w./-]+\.(?:json|ts|yml|md))(?::\d+)?`/g)].map(
            (m) => m[1] ?? "",
        )
        claims.push({ section, claim, evidence, scope, limitation, status, files })
    }
    return claims
}

function evalEntries(): EvalEntry[] {
    return readdirSync(EVALS)
        .filter((name) => name !== "fixtures" && statSync(join(EVALS, name)).isDirectory())
        .sort()
        .map((name) => {
            const dir = join(EVALS, name)
            const readme = join(dir, "README.md")
            const title = existsSync(readme)
                ? (readFileSync(readme, "utf8").split("\n")[0] ?? "").replace(/^#\s*/, "")
                : name
            const results = walk(dir).filter((path) => path.endsWith("results.json"))
            const latest = results
                .map((path) =>
                    when(
                        JSON.parse(readFileSync(join(dir, path), "utf8")) as Record<
                            string,
                            unknown
                        >,
                    ),
                )
                .filter((value): value is string => value !== undefined)
                .sort()
                .at(-1)
            return { name, title, results, ...(latest === undefined ? {} : { measuredAt: latest }) }
        })
}

/** A result's own timestamp, under whichever key its script used. */
function when(result: Record<string, unknown>): string | undefined {
    for (const key of ["measuredAt", "startedAt", "ranAt"]) {
        const value = result[key]
        if (typeof value === "string") return value
    }
    return undefined
}

function walk(dir: string, prefix = ""): string[] {
    return readdirSync(dir).flatMap((name) => {
        const full = join(dir, name)
        const rel = prefix === "" ? name : `${prefix}/${name}`
        return statSync(full).isDirectory() ? walk(full, rel) : [rel]
    })
}

function render(claims: readonly Claim[], evals: readonly EvalEntry[]): string {
    const count = (status: string) => claims.filter((c) => c.status.startsWith(status)).length
    const lines = [
        "# Evaluations",
        "",
        "<!-- Generated by `bun scripts/eval-index.ts` from `evals/CLAIMS.md` and each eval's directory. Do not edit. -->",
        "",
        "Every number Dispach states in public has a row in [`CLAIMS.md`](CLAIMS.md) naming the file it",
        "comes from. Negative results are listed with the positive ones.",
        "",
        `**${claims.length} claims:** ${count("verified")} verified, ${count("cite")} cited from external research, ${count("needs-run")} waiting on a run, ${count("fix")} to fix, ${count("remove")} removed.`,
        "",
        "| Eval | What it measures | Committed results | Last measured |",
        "| --- | --- | --- | --- |",
        ...evals.map(
            (entry) =>
                `| [\`${entry.name}\`](${entry.name}/) | ${entry.title} | ${entry.results.length === 0 ? "none" : entry.results.map((r) => `[\`${r}\`](${entry.name}/${r})`).join(", ")} | ${entry.measuredAt?.slice(0, 10) ?? "not recorded"} |`,
        ),
        "",
        "## Claims not yet backed by a committed run",
        "",
        ...claims
            .filter((c) => !c.status.startsWith("verified") && !c.status.startsWith("cite"))
            .map((c) => `- ${c.claim} — **${c.status}**. ${c.limitation}`),
        "",
    ]
    return lines.join("\n")
}

const claims = parseClaims(readFileSync(join(EVALS, "CLAIMS.md"), "utf8"))
const evals = evalEntries()
const readme = render(claims, evals)
const feed = `${JSON.stringify({ claims, evals }, null, 4)}\n`

const missing = claims.flatMap((claim) => {
    if (!claim.status.startsWith("verified")) return []
    if (claim.files.length === 0) return [`"${claim.claim}" is verified but names no file`]
    return claim.files
        .filter((file) => !existsSync(join(ROOT, file)) && !existsSync(join(EVALS, file)))
        .map((file) => `"${claim.claim}" cites ${file}, which does not exist`)
})

if (CHECK) {
    const stale = [
        ["evals/README.md", readme],
        ["evals/index.json", feed],
    ].filter(
        ([path = "", text]) =>
            !existsSync(join(ROOT, path)) || readFileSync(join(ROOT, path), "utf8") !== text,
    )
    for (const problem of missing) console.error(`eval-index: ${problem}`)
    for (const [path] of stale) console.error(`eval-index: ${path} is stale`)
    if (missing.length > 0 || stale.length > 0) {
        console.error(
            "  hint: fix the claim's evidence column, or run `bun run evals:index` and commit the result.",
        )
        process.exit(1)
    }
    console.log(`eval index: current, ${claims.length} claims, ${evals.length} evals`)
} else {
    if (missing.length > 0) {
        for (const problem of missing) console.error(`eval-index: ${problem}`)
        process.exit(1)
    }
    writeFileSync(join(EVALS, "README.md"), readme)
    writeFileSync(join(EVALS, "index.json"), feed)
    console.log(
        `eval index: wrote evals/README.md and evals/index.json (${claims.length} claims, ${evals.length} evals)`,
    )
}
